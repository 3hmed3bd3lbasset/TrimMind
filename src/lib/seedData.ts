const getIsoSlot = (offsetDays = 0, timeStr = '15:00') => {
  const d = new Date();
  d.setDate(d.getDate() + offsetDays);
  const datePart = d.toISOString().split('T')[0];
  return `${datePart}T${timeStr}:00.000Z`;
};

